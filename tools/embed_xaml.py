"""Embed the editable HUD views in the game mode's cooked SCAR sources."""

import argparse
from pathlib import Path
from xml.etree import ElementTree


root = Path(__file__).resolve().parents[1]
output = root / "Mods/aoe4_dota_mod/project/source/scar/ui/lane_wars_views.scar"
lines = ["-- Generated by tools/embed_xaml.py from authoring/ui.", "LaneWarsSoloViews = {\n"]
for view, filename in (("draft", "hero-draft.xaml"), ("battle", "match-hud.xaml")):
    xaml = (root / "authoring/ui" / filename).read_text(encoding="utf-8")
    ElementTree.fromstring(xaml)
    if "]==]" in xaml:
        raise SystemExit(f"{filename} contains the SCAR string delimiter")
    lines.append(f"\t{view} = [==[\n{xaml}]==],\n")
contents = lines[0] + "\n" + "".join(lines[1:]) + "}\n"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
if parser.parse_args().check:
    if not output.exists() or output.read_text(encoding="utf-8") != contents:
        raise SystemExit("Run tools/embed_xaml.py to refresh the embedded views")
else:
    output.write_text(contents, encoding="utf-8", newline="\n")
